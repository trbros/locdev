import { ExternalLink, Search } from "lucide-react";
import { useMemo, useState } from "react";

import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import data from "@/generated/third-party.json";
import { openInBrowser } from "@/lib/system";
import { cn } from "@/lib/utils";
import { t } from "@/lib/i18n";

interface Item {
  name: string;
  version: string;
  license: string;
  url: string | null;
}

const SETS: { id: "rust" | "npm"; label: string }[] = [
  { id: "rust", label: t("Rust crates") },
  { id: "npm", label: t("npm packages") },
];

/** Every third-party package in LocDev with its declared license
 * (generated by `make third-party` from cargo and pnpm). */
export default function ThirdParty({ onClose }: { onClose: () => void }) {
  const [set, setSet] = useState<"rust" | "npm">("rust");
  const [query, setQuery] = useState("");
  const items = (data as { rust: Item[]; npm: Item[] })[set];
  const needle = query.trim().toLowerCase();
  const shown = needle
    ? items.filter((i) => i.name.toLowerCase().includes(needle) || i.license.toLowerCase().includes(needle))
    : items;
  // The most common licenses, for the summary line.
  const licenses = useMemo(() => {
    const count = new Map<string, number>();
    for (const i of items) count.set(i.license, (count.get(i.license) ?? 0) + 1);
    return [...count.entries()].sort((a, b) => b[1] - a[1]).slice(0, 4);
  }, [items]);

  return (
    <Dialog open onOpenChange={(open) => !open && onClose()}>
      <DialogContent className="sm:max-w-2xl">
        <DialogHeader>
          <DialogTitle>{t("Third-party software")}</DialogTitle>
          <DialogDescription>
            {t(
              "The packages inside LocDev's app, daemon and CLI, with the licenses their authors declare. Each keeps its own copyright and license.",
            )}
          </DialogDescription>
        </DialogHeader>
        <div className="flex items-center gap-2">
          <div role="tablist" aria-label={t("Kind")} className="flex gap-1">
            {SETS.map((s) => (
              <button
                type="button"
                role="tab"
                key={s.id}
                aria-selected={set === s.id}
                onClick={() => setSet(s.id)}
                className={cn(
                  "rounded-md px-2.5 py-1 text-[13px] text-muted-foreground hover:text-foreground",
                  set === s.id && "bg-foreground/6 text-foreground",
                )}
              >
                {s.label} <span className="font-mono text-[11px]">{(data as Record<string, Item[]>)[s.id].length}</span>
              </button>
            ))}
          </div>
          <div className="relative ml-auto w-56">
            <Search className="absolute top-1/2 left-2.5 size-3.5 -translate-y-1/2 text-muted-foreground" />
            <Input
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder={t("Name or license")}
              aria-label={t("Name or license")}
              className="h-8 pl-8"
            />
          </div>
        </div>
        <p className="font-mono text-[11px] text-muted-foreground">
          {licenses.map(([license, n]) => `${license} ${n}`).join(" · ")}
        </p>
        <ul className="max-h-[50vh] divide-y overflow-y-auto" data-selectable>
          {shown.map((i) => (
            <li key={`${i.name}@${i.version}`} className="flex items-center gap-3 py-1.5 text-[13px]">
              <span className="min-w-0 flex-1 truncate">
                <span className="font-mono">{i.name}</span>{" "}
                <span className="font-mono text-[11.5px] text-muted-foreground">{i.version}</span>
              </span>
              <span className="max-w-[45%] truncate text-[12px] text-muted-foreground">{i.license}</span>
              {i.url && (
                <button
                  type="button"
                  aria-label={t("Open {name}", { name: i.name })}
                  onClick={() => i.url && openInBrowser(i.url)}
                  className="text-muted-foreground hover:text-foreground"
                >
                  <ExternalLink className="size-3.5" />
                </button>
              )}
            </li>
          ))}
        </ul>
      </DialogContent>
    </Dialog>
  );
}
