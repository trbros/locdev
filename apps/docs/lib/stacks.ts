export function frameworkRequestUrl(name?: string) {
	const params = new URLSearchParams({
		title: name
			? `Framework integration: ${name}`
			: "Framework integration request",
		body: `## Framework
${name ?? "Name and official documentation URL"}

## Development command
Command, host and port options

## Requested integration
Automatic detection, runtime, or suggested commands

## Use case
How this would improve your local workflow`,
	});
	return `${repository.issues}?${params}`;
}
